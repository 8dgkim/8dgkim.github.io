MATH = '''<link rel="stylesheet" href="../../assets/katex/katex.min.css">
<script defer src="../../assets/katex/katex.min.js"></script>
<script defer src="../../js/math.js"></script>
'''
tm = lambda d: f'<time datetime="{esc(d)}">{esc(d)}</time>'

def dates(p):
    m = p['meta']; bits = [tm(m['date'])]
    if m['published'] != m['date']: bits.append('published ' + tm(m['published']))
    if m.get('updated'): bits.append('updated ' + tm(m['updated']))
    return ' · '.join(bits)

def page(p, md, index):
    m = p['meta']; body = callouts(md.render(obsidian(p['body'], p, index)))
    body = body.replace('<table>', '<div class="tablewrap"><table>').replace('</table>', '</table></div>')   # wide tables scroll on their own
    has_math = '<span class="math">' in body or '<div class="math">' in body
    url = f'{SITE_URL}/{p["section"]}/{p["slug"]}/'
    return PAGE.substitute(
        mark=MARK, lang=esc(m.get('lang', 'en')), title=esc(m['title']), site=esc(SITE_NAME), desc=esc(m.get('description', '')), url=esc(url),
        ogimage=f'<meta property="og:image" content="{esc(url + m["image"])}">\n' if m.get('image') else '',
        math=MATH if has_math else '', sub=f'      <p class="sub">{esc(m["subtitle"])}</p>\n' if m.get('subtitle') else '',
        dates=dates(p), body=body.rstrip())   # not indented: indentation would end up inside <pre> code

def write(path, content):
    if path.exists() and MARK not in path.read_text(encoding='utf-8')[:400]:
        print(f'  not written: {path.relative_to(ROOT)} exists and was not made by this script'); return False
    if not path.exists() or path.read_text(encoding='utf-8') != content: path.write_text(content, encoding='utf-8'); print(f'  wrote {path.relative_to(ROOT)}')
    return True

# ---------------- the home page lists ----------------
def item(p):
    m = p['meta']; href = m.get('link') or f'{p["section"]}/{p["slug"]}/'
    two = lambda tag_en, tag_ko, cls: (f'<span class="{cls}i18n" lang="en">{tag_en}</span><span class="{cls}i18n" lang="ko">{tag_ko}</span>'
                                       if tag_ko else (f'<span class="{cls.strip()}">{tag_en}</span>' if cls else tag_en))
    def pair(k, cls):   # both languages if both are given, else the one there is
        en, ko = m.get(f'{k}_en'), m.get(f'{k}_ko')
        if en and ko: return two(esc(en), esc(ko), cls)
        return two(esc(en or ko), '', cls) if (en or ko) else ''
    title = pair('title', '') or esc(m['title']); desc = pair('description', 'desc ')
    return f'      <li>{tm(m["date"])}<a href="{esc(href)}">{title}</a>{desc}</li>'

def home(posts):
    path = ROOT / 'index.html'; s = path.read_text(encoding='utf-8'); new = s
    for section, sid in (('notes', 'notes-h'), ('operations', 'ops-h')):
        items = sorted((p for p in posts if p['section'] == section), key=lambda p: (p['meta']['date'], p['slug']), reverse=True)
        block = f'<!-- build:{section} (made by tools/build.py) -->\n' + '\n'.join(item(p) for p in items) + ('\n' if items else '') + f'      <!-- /build:{section} -->'
        new, n = re.subn(rf'<!-- build:{section}\b.*?<!-- /build:{section} -->', lambda _: block, new, flags=re.S)
        if not n: print(f'  warning: index.html has no <!-- build:{section} --> markers'); continue
        # a section shows once it has something in it
        new = re.sub(rf'<section aria-labelledby="{sid}"( hidden)?>', f'<section aria-labelledby="{sid}"' + ('' if items else ' hidden') + '>', new)
    if new != s: path.write_text(new, encoding='utf-8'); print('  wrote index.html (lists)')

def main():
    posts = collect(); md = markdown()
    index = {}
    for p in posts:
        index[p['slug'].lower()] = p
        for k in ('title_en', 'title_ko'):
            if p['meta'].get(k): index[str(p['meta'][k]).lower()] = p
    for p in posts:
        if not p['meta'].get('link'): write(p['folder'] / 'index.html', page(p, md, index))
    home(posts)
    # pages made by this script whose index.md is gone
    for section in SECTIONS:
        for f in (ROOT / section).glob('*/index.html') if (ROOT / section).is_dir() else []:
            if not (f.parent / 'index.md').exists() and MARK in f.read_text(encoding='utf-8')[:400]:
                print(f'  stale: {f.relative_to(ROOT)} has no index.md any more (delete the folder, or bring the .md back)')
    print(f'built {sum(1 for p in posts if not p["meta"].get("link"))} pages, {len(posts)} list entries')

if __name__ == '__main__':
    main()
