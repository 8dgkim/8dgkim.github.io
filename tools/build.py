#!/usr/bin/env python3
"""
build.py : turn the site's Markdown posts into pages, and list them on the home page.

    python3 tools/build.py

Posts are folders with an index.md, and their images and videos in a figures/ subfolder:
    notes/<yyyy-mm-dd>/index.md          writing; the folder is the day it is published
    operations/<yyyy-mm-dd>/index.md     projects; the folder is the day it happened
(A second post on the same day: <yyyy-mm-dd>-2.) Folders starting with _ (like notes/_template) are skipped.

Properties at the top of index.md (Obsidian's "Properties" are exactly this):
    title_en, title_ko               the title in English and/or Korean (at least one)
    description_en, description_ko   one line, for the home page list and link previews
    subtitle_en, subtitle_ko         optional: a line under the title
    The post page uses the post's own language (lang); the home page shows each language where it is given,
    and the other language where it is not.
    date           when it happened (operations) or was published (notes); default: the folder name
    published      default: date
    updated        optional
    link           optional: the list entry links here instead (a project that lives elsewhere); no page is built
    image          optional: picture for link previews (a file in the folder)
    lang           optional: en (default) or ko, the language the post is written in
    draft          optional: true keeps it off the site

Markdown: CommonMark, tables, strikethrough, footnotes, $math$ and $$math$$ (typeset by KaTeX in the browser), and
from Obsidian: ![[file]] embeds (images and videos), [[links]] to other posts, > [!note] callouts, ==highlight==,
%% comments %%. Embed options after |: a caption, "wide" (wider than the text), a crop like 16:9.
Several embeds on one line make a row: ![[a.jpg|9:16]] ![[b.jpg|9:16]].

The pages it writes start with a marker comment; it never overwrites a file without that marker.
"""
import datetime, html, re, sys
from pathlib import Path
from string import Template
import yaml
from markdown_it import MarkdownIt
from mdit_py_plugins.dollarmath import dollarmath_plugin
from mdit_py_plugins.footnote import footnote_plugin

ROOT = Path(__file__).resolve().parent.parent
SITE_NAME, SITE_URL = 'Kim DongGyu', 'https://8dgkim.github.io'
SECTIONS = ('notes', 'operations')
MARK = '<!-- generated by tools/build.py from index.md: edit that file, not this one -->'
FOLDER = re.compile(r'^\d{4}-\d{2}-\d{2}(-\d+)?$')
VIDEO = {'.mp4', '.webm', '.mov', '.m4v'}
IMAGE = {'.jpg', '.jpeg', '.png', '.gif', '.webp', '.svg', '.avif'}
esc = lambda s: html.escape(str(s), quote=True)

# ---------------- reading posts ----------------
def read_post(section, folder):
    text = (folder / 'index.md').read_text(encoding='utf-8')
    meta, body = {}, text
    m = re.match(r'^---\s*\n(.*?)\n---\s*\n?', text, re.S)
    if m:
        try: meta, body = (yaml.safe_load(m.group(1)) or {}), text[m.end():]
        except yaml.YAMLError as e:
            print(f'  skipped {section}/{folder.name}: its properties are not valid YAML ({str(e).splitlines()[0]});'
                  ' put quotes around a value that contains ": " or starts with a special character'); return None
    day = folder.name[:10]
    meta = {k: (v.isoformat() if isinstance(v, (datetime.date, datetime.datetime)) else v) for k, v in meta.items()}
    lang = meta.get('lang', 'en')
    for k in ('title', 'subtitle', 'description'):   # the post's own language, else the other one
        en, ko = meta.get(f'{k}_en'), meta.get(f'{k}_ko')
        meta[k] = (ko if lang == 'ko' else en) or en or ko
    meta['title'] = meta['title'] or folder.name
    meta.setdefault('date', day); meta.setdefault('published', meta['date'])
    return {'section': section, 'folder': folder, 'slug': folder.name, 'meta': meta, 'body': body}

def collect():
    posts = []
    for section in SECTIONS:
        base = ROOT / section
        if not base.is_dir(): continue
        for folder in sorted(base.iterdir()):
            if folder.is_dir() and FOLDER.match(folder.name) and (folder / 'index.md').is_file():
                p = read_post(section, folder)
                if p and not p['meta'].get('draft'): posts.append(p)
            elif folder.is_dir() and not folder.name.startswith('_') and not folder.name.startswith('.'):
                print(f'  skipped {section}/{folder.name}: ' + ('no index.md' if FOLDER.match(folder.name) else 'folder name is not yyyy-mm-dd'))
    return posts

# ---------------- Obsidian syntax, before Markdown ----------------
def embed(target, opts, folder):
    """![[file|options]] -> a figure (image or video); options: caption, 'wide', a crop like 16:9."""
    caption, wide, ar = '', False, None
    for o in opts:
        o = o.strip()
        if o == 'wide': wide = True
        elif re.fullmatch(r'\d+(\.\d+)?:\d+(\.\d+)?', o): a, b = o.split(':'); ar = float(a) / float(b)
        elif re.fullmatch(r'\d+(x\d+)?', o): pass   # Obsidian's pixel width: the layout decides here
        elif o: caption = o
    src = target.strip(); ext = Path(src).suffix.lower(); style = f' style="--ar: {ar:.4f}"' if ar else ''
    if not (folder / src).exists(): print(f'  warning: {folder.relative_to(ROOT)}/{src} is embedded but missing')
    if ext in VIDEO:
        poster = next((f for f in (str(Path(src).with_suffix('.poster.jpg')), str(Path(src).with_suffix('.jpg'))) if (folder / f).exists()), None)
        media = f'<video src="{esc(src)}"' + (f' poster="{esc(poster)}"' if poster else '') + f' controls playsinline preload="metadata"{style}></video>'
    else:
        media = f'<img src="{esc(src)}" alt="{esc(caption or Path(src).stem)}" loading="lazy"{style}>'
    cls = ' class="wide"' if wide else ''
    return f'<figure{cls}>{media}' + (f'<figcaption>{esc(caption)}</figcaption>' if caption else '') + '</figure>'

EMBED = re.compile(r'!\[\[([^\]|]+)((?:\|[^\]]*)?)\]\]')
WIKI = re.compile(r'(?<!!)\[\[([^\]|]+)(?:\|([^\]]+))?\]\]')

def obsidian(body, post, index):
    folder, out, fence = post['folder'], [], None
    body = re.sub(r'%%.*?%%', '', body, flags=re.S)   # Obsidian comments
    for line in body.split('\n'):
        f = re.match(r'^\s*(```|~~~)', line)
        if f:
            fence = None if fence == f.group(1) else (fence or f.group(1)); out.append(line); continue
        if fence: out.append(line); continue
        parts = re.split(r'(`[^`]*`)', line)   # leave inline code alone
        for i in range(0, len(parts), 2):
            s = parts[i]
            s = re.sub(r'==([^=\n]+)==', r'<mark>\1</mark>', s)
            s = WIKI.sub(lambda m: wikilink(m.group(1), m.group(2), post, index), s)
            parts[i] = s
        line = ''.join(parts)
        embeds = EMBED.findall(line)
        if embeds and not EMBED.sub('', line).strip():
            figs = [embed(t, o.split('|')[1:], folder) for t, o in embeds]
            if len(figs) == 1: out += ['', figs[0], '']
            else: out += ['', f'<div class="gallery" style="--n: {len(figs)}">' + ''.join(figs) + '</div>', '']
        else:
            out.append(EMBED.sub(lambda m: embed(m.group(1), m.group(2).split('|')[1:], folder), line))
    return '\n'.join(out)

def wikilink(target, text, post, index):
    key = target.strip().lower(); hit = index.get(key)
    label = esc(text or target)
    if not hit: print(f'  note: [[{target}]] in {post["section"]}/{post["slug"]} matches no post'); return label
    href = f'../../{hit["section"]}/{hit["slug"]}/' if not hit['meta'].get('link') else hit['meta']['link']
    return f'<a href="{esc(href)}">{label}</a>'

# ---------------- Markdown ----------------
def markdown():
    md = MarkdownIt('commonmark', {'html': True, 'typographer': True}).enable(['table', 'strikethrough', 'replacements', 'smartquotes'])
    md.use(footnote_plugin).use(dollarmath_plugin, allow_space=True, double_inline=True)
    # math stays as TeX between \( \) and \[ \]; js/math.js typesets it with KaTeX
    md.add_render_rule('math_inline', lambda self, t, i, o, e: f'<span class="math">\\({esc(t[i].content)}\\)</span>')
    md.add_render_rule('math_inline_double', lambda self, t, i, o, e: f'<span class="math">\\[{esc(t[i].content)}\\]</span>')
    md.add_render_rule('math_block', lambda self, t, i, o, e: f'<div class="math">\\[{esc(t[i].content)}\\]</div>\n')
    md.add_render_rule('math_block_label', lambda self, t, i, o, e: f'<div class="math">\\[{esc(t[i].content)}\\]</div>\n')
    return md

def callouts(h):
    """> [!note] Title -> a box with a label (Obsidian callouts)."""
    def box(m):
        kind, title = m.group(1).lower(), (m.group(2) or '').strip()
        return f'<blockquote class="box callout callout-{esc(kind)}">\n<p><span class="label">{title or esc(kind.capitalize())}</span>'
    return re.sub(r'<blockquote>\s*<p>\[!(\w+)\][+-]?([^\n<]*)(?:\n|(?=</p>))', box, h)

# ---------------- pages ----------------
